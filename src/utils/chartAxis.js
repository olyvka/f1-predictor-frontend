// Діапазон осі часу (кола, сектори): від мінімуму до максимуму даних із
// запасом ~1%. Без нього Recharts починає вісь з нуля, і лінії з часом
// ~90 с стискаються в смужку внизу графіка.
export const timeDomain = [
  (min) => Math.max(0, min - Math.max(0.2, Math.abs(min) * 0.01)),
  (max) => max + Math.max(0.2, Math.abs(max) * 0.01),
];
